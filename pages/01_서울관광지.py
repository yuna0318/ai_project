# -----------------------------
# Folium 지도 생성
# -----------------------------
m = folium.Map(
    location=[37.5665, 126.9780],
    zoom_start=11,
    tiles="CartoDB Voyager"  # 컬러 지도
)

# -----------------------------
# 마커 추가
# -----------------------------
for name, info in places.items():

    popup_html = f"""
    <b>{name}</b><br>
    가까운 역: {info['station']}
    """

    folium.Marker(
        location=[info["lat"], info["lon"]],
        popup=popup_html,
        tooltip=name,
        icon=folium.Icon(
            color="blue",
            icon="info-sign"
        )
    ).add_to(m)

# -----------------------------
